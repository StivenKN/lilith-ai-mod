export const catalogs: Record<UiLocale, Messages> = { en, es };

type Params<S extends string> = S extends `${string}{${infer P}}${infer Rest}` ? P | Params<Rest> : never;
type ParamArgs<K extends MessageKey> = [Params<(typeof en)[K]>] extends [never]
  ? []
  : [params: Record<Params<(typeof en)[K]>, string | number>];

export function t<K extends MessageKey>(locale: UiLocale, key: K, ...[params]: ParamArgs<K>): string {
  const template: string = catalogs[locale][key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = (params as Record<string, string | number>)[name];
    return value === undefined ? match : String(value);
  });
}

/** Binds a locale once: `const tr = translator("es"); tr("plugin.send")`. */
export const translator =
  (locale: UiLocale) =>
  <K extends MessageKey>(key: K, ...params: ParamArgs<K>): string =>
    t(locale, key, ...params);
export type Translate = ReturnType<typeof translator>;
